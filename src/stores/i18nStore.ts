interface I18nStore {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: (key: string) => string;
}

export const useI18n = create<I18nStore>((set, get) => ({
  language: "zh",
  setLanguage: (lang) => {
    set({ language: lang });
    invoke("rebuild_menu", { lang }).catch(() => {});
  },
  t: (key) => {
    const { language } = get();
    const entry = translations[key];
    if (!entry) return key;
    return entry[language] || entry.zh || key;
  },
}));
